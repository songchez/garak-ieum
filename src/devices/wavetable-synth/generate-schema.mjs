// The JSON manifest is the only authoring source for scalar IDs and DSP limits.
// Run this file after editing schema.json; --check verifies committed artifacts.
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const schema = JSON.parse(await readFile(resolve(here, 'schema.json'), 'utf8'))
for (const [name, entries] of [['params', schema.params], ['modulationSources', schema.modulationSources]]) {
  if (entries.some((entry, index) => entry.index !== index) || new Set(entries.map(entry => entry.id)).size !== entries.length || new Set(entries.map(entry => entry.cpp)).size !== entries.length) {
    throw new Error(`${name}: IDs must be unique and explicitly indexed in wire order`)
  }
}
for (const parameter of schema.params) {
  if (![parameter.min, parameter.max, parameter.default].every(Number.isFinite) || parameter.min >= parameter.max || parameter.default < parameter.min || parameter.default > parameter.max ||
      (parameter.options && (parameter.options.length > 8 || !parameter.options.some(option => option.value === parameter.default) || parameter.options.some(option => !Number.isFinite(option.value) || option.value < parameter.min || option.value > parameter.max)))) {
    throw new Error(`Invalid parameter bounds, default, or options: ${parameter.id}`)
  }
}
if (schema.factoryBanks.length !== schema.limits.factoryBanks || schema.factoryBanks.some((bank, index) =>
  bank.index !== index || bank.harmonics.length !== schema.limits.factoryFrames || bank.harmonics.some(frame => frame.length !== schema.limits.factoryHarmonics || !frame.every(Number.isFinite)))) {
  throw new Error('Factory spectra must match the declared bank/frame/harmonic limits')
}
const text = JSON.stringify(schema)
let fingerprint = 2166136261
for (const byte of new TextEncoder().encode(text)) fingerprint = Math.imul(fingerprint ^ byte, 16777619) >>> 0
const float = value => `${Number.isInteger(value) ? value.toFixed(1) : value}f`
const cArray = values => values.map(float).join(', ')
const boolArray = key => schema.params.map(p => p[key] ? 'true' : 'false').join(', ')
const limits = schema.limits
const generatedTs = `// GENERATED by generate-schema.mjs. Edit schema.json instead.\n` +
  `export const WAVE_SCHEMA_FINGERPRINT = ${fingerprint} as const\n` +
  `export const WAVE_LIMITS = ${JSON.stringify(limits, null, 2)} as const\n` +
  `export const WAVE_PARAMETER_SCHEMA = ${JSON.stringify(schema.params, null, 2)} as const\n` +
  `export type WavetableParamId = typeof WAVE_PARAMETER_SCHEMA[number]['id']\n` +
  `export const WAVE_MODULATION_SOURCES = ${JSON.stringify(schema.modulationSources, null, 2)} as const\n` +
  `export type WavetableModSource = typeof WAVE_MODULATION_SOURCES[number]['id']\n` +
  `export const WAVE_FACTORY_BANKS = ${JSON.stringify(schema.factoryBanks, null, 2)} as const\n`
const constants = {
  kOscillators: limits.oscillators, kMaxPolyphony: limits.polyphony,
  kMaxUnison: limits.unison, kEnvelopes: limits.envelopes,
  kLfos: limits.lfos, kLfoPoints: limits.lfoPoints, kMacros: limits.macros,
  kMaxModRoutes: limits.routes, kWavetableSize: limits.frameSize,
  kMaxUserBanks: limits.customBanks, kMaxFrames: limits.framesPerBank,
  kFactoryBankCount: limits.factoryBanks, kFactoryFrames: limits.factoryFrames,
  kFactoryHarmonicCount: limits.factoryHarmonics,
}
const generatedCpp = `// GENERATED by src/devices/wavetable-synth/generate-schema.mjs.\n` +
  `#pragma once\n#include <array>\n#include <cstddef>\n#include <cstdint>\n\nnamespace ieum::wave::generated {\n` +
  `inline constexpr std::uint32_t kSchemaVersion = 1;\n` +
  `inline constexpr std::uint32_t kSchemaFingerprint = ${fingerprint}u;\n` +
  `inline constexpr std::size_t kParamCount = ${schema.params.length};\n` +
  Object.entries(constants).map(([key, value]) => `inline constexpr std::size_t ${key} = ${value};\n`).join('') +
  `enum class ParameterId : std::uint16_t {\n` +
  schema.params.map(p => `  ${p.cpp} = ${p.index},\n`).join('') + `  Count = ${schema.params.length}\n};\n` +
  `enum class ModSource : std::uint8_t {\n` +
  schema.modulationSources.map(s => `  ${s.cpp} = ${s.index},\n`).join('') + `  Count = ${schema.modulationSources.length}\n};\n` +
  `inline constexpr std::uint32_t kNoAuxSource = 0xffffffffu;\n` +
  `inline constexpr std::array<const char*, kParamCount> kParameterNames = {{${schema.params.map(p => JSON.stringify(p.id)).join(', ')}}};\n` +
  `inline constexpr std::array<float, kParamCount> kDefaults = {{${cArray(schema.params.map(p => p.default))}}};\n` +
  `inline constexpr std::array<float, kParamCount> kMinimum = {{${cArray(schema.params.map(p => p.min))}}};\n` +
  `inline constexpr std::array<float, kParamCount> kMaximum = {{${cArray(schema.params.map(p => p.max))}}};\n` +
  `inline constexpr std::array<bool, kParamCount> kLogarithmic = {{${schema.params.map(p => p.scale === 'log' ? 'true' : 'false').join(', ')}}};\n` +
  `inline constexpr std::array<bool, kParamCount> kModulatable = {{${boolArray('modulate')}}};\n` +
  `inline constexpr std::array<bool, kParamCount> kInteger = {{${schema.params.map(p => p.integer || p.options?.every(o => Number.isInteger(o.value)) ? 'true' : 'false').join(', ')}}};\n` +
  `inline constexpr std::array<std::uint8_t, kParamCount> kOptionCount = {{${schema.params.map(p => p.options?.length ?? 0).join(', ')}}};\n` +
  `inline constexpr float kOptionValues[kParamCount][8] = {\n${schema.params.map(p => `  {${cArray(p.options?.map(o => o.value) ?? [0])}}`).join(',\n')}\n};\n` +
  `inline constexpr float kFactoryHarmonics[${limits.factoryBanks}][${limits.factoryFrames}][${limits.factoryHarmonics}] = {\n` +
  schema.factoryBanks.map(bank => `  {\n${bank.harmonics.map(frame => `    {${cArray(frame)}}`).join(',\n')}\n  }`).join(',\n') +
  `\n};\n} // namespace ieum::wave::generated\n`

let stale = false
for (const [path, contents] of [
  [resolve(here, 'schema.generated.ts'), generatedTs],
  [resolve(here, '../../..', 'native/devices/wavetable-synth/generated/patch_schema.hpp'), generatedCpp],
]) {
  if (process.argv.includes('--check')) {
    const existing = await readFile(path, 'utf8').catch(() => '')
    // Git may check text out with CRLF. Only that newline difference is ignored;
    // generated content and the semantic schema fingerprint remain unchanged.
    if (existing.replace(/\r\n/g, '\n') !== contents) { console.error(`Stale generated schema: ${path}`); stale = true }
  } else {
    await mkdir(dirname(path), { recursive: true })
    await writeFile(path, contents)
  }
}
if (stale) process.exitCode = 1
