// The JSON manifest is the only authoring source for scalar IDs and DSP limits.
// Run this file after editing schema.json; --check verifies committed artifacts.
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const schema = JSON.parse(await readFile(resolve(here, 'schema.json'), 'utf8'))
for (const [name, entries] of [['params', schema.params], ['modulationSources', schema.modulationSources]]) {
  if (entries.some((entry, index) => entry.index !== index) || new Set(entries.map(entry => entry.id)).size !== entries.length || new Set(entries.map(entry => entry.cpp)).size !== entries.length) {
    throw new Error(`${name}: IDs must be unique and explicitly indexed in wire order`)
  }
}
for (const parameter of schema.params) {
  if (![parameter.min, parameter.max, parameter.default].every(Number.isFinite) || parameter.min >= parameter.max || parameter.default < parameter.min || parameter.default > parameter.max ||
      (parameter.options && (parameter.options.length > 8 || !parameter.options.some(option => option.value === parameter.default) || parameter.options.some(option => !Number.isFinite(option.value) || option.value < parameter.min || option.value > parameter.max)))) {
    throw new Error(`Invalid parameter bounds, default, or options: ${parameter.id}`)
  }
}
if (schema.factoryBanks.length !== schema.limits.factoryBanks || schema.factoryBanks.some((bank, index) =>
  bank.index !== index || bank.harmonics.length !== schema.limits.factoryFrames || bank.harmonics.some(frame => frame.length !== schema.limits.factoryHarmonics || !frame.every(Number.isFinite)))) {
  throw new Error('Factory spectra must match the declared bank/frame/harmonic limits')
}
const text = JSON.stringify(schema)
let fingerprint = 2166136261
for (const byte of new TextEncoder().encode(text)) fingerprint = Math.imul(fingerprint ^ byte, 16777619) >>> 0
const limits = schema.limits
const generatedTs = `// GENERATED by generate-schema.mjs. Edit schema.json instead.\n` +
  `export const WAVE_SCHEMA_FINGERPRINT = ${fingerprint} as const\n` +
  `export const WAVE_LIMITS = ${JSON.stringify(limits, null, 2)} as const\n` +
  `export const WAVE_PARAMETER_SCHEMA = ${JSON.stringify(schema.params, null, 2)} as const\n` +
  `export type WavetableParamId = typeof WAVE_PARAMETER_SCHEMA[number]['id']\n` +
  `export const WAVE_MODULATION_SOURCES = ${JSON.stringify(schema.modulationSources, null, 2)} as const\n` +
  `export type WavetableModSource = typeof WAVE_MODULATION_SOURCES[number]['id']\n` +
  `export const WAVE_FACTORY_BANKS = ${JSON.stringify(schema.factoryBanks, null, 2)} as const\n`
// The synth's own copy (rust/garak-engine/src/wave/schema.rs), laid out the way rustfmt formats it with
// the workspace settings (rust/rustfmt.toml: max_width 110), so `cargo fmt --check` accepts it unchanged.
const constants = {
  OSCILLATORS: limits.oscillators, MAX_POLYPHONY: limits.polyphony,
  MAX_UNISON: limits.unison, ENVELOPES: limits.envelopes,
  LFOS: limits.lfos, LFO_POINTS: limits.lfoPoints, MACROS: limits.macros,
  MAX_MOD_ROUTES: limits.routes, WAVETABLE_SIZE: limits.frameSize,
  MAX_USER_BANKS: limits.customBanks, MAX_FRAMES: limits.framesPerBank,
  FACTORY_BANK_COUNT: limits.factoryBanks, FACTORY_FRAMES: limits.factoryFrames,
  FACTORY_HARMONIC_COUNT: limits.factoryHarmonics,
}
const MAX_WIDTH = 110
const rustFloat = value => Number.isInteger(value) ? value.toFixed(1) : String(value)
const optionValues = parameter => { const values = parameter.options?.map(option => option.value) ?? []; return [...values, ...Array(8 - values.length).fill(0)] }
// rustfmt's array layout: one line when it fits; otherwise short items (<= 10 characters) fill lines and
// longer ones (nested arrays, strings) go one per line, each with a trailing comma. `column`: where `[` starts.
function rustArray(items, indent, column) {
  const flat = typeof items[0] === 'string' ? items : null
  const inline = items.map(item => typeof item === 'string' ? item : rustArray(item, indent + 4, 0))
  const single = `[${inline.join(', ')}]`
  if (!single.includes('\n') && column + single.length <= MAX_WIDTH - 2) return single
  const pad = ' '.repeat(indent + 4)
  if (flat && flat.every(item => item.length <= 10)) {
    const lines = []
    let line = ''
    for (const item of flat) {
      const next = line ? `${line} ${item},` : `${item},`
      if (pad.length + next.length >= MAX_WIDTH && line) { lines.push(line); line = `${item},` } else line = next
    }
    lines.push(line)
    return `[\n${lines.map(text => pad + text).join('\n')}\n${' '.repeat(indent)}]`
  }
  return `[\n${items.map(item => `${pad}${typeof item === 'string' ? item : rustArray(item, indent + 4, indent + 4)},`).join('\n')}\n${' '.repeat(indent)}]`
}
const rustConst = (name, type, items) => { const head = `pub const ${name}: ${type} = `; return `${head}${rustArray(items, 0, head.length)};\n` }
const floats = values => values.map(rustFloat)
const bools = values => values.map(value => value ? 'true' : 'false')
const generatedRust = `//! GENERATED by src/devices/wavetable-synth/generate-schema.mjs from schema.json. Do not edit: run\n` +
  `//! \`node src/devices/wavetable-synth/generate-schema.mjs\` after editing the manifest.\n` +
  `#![allow(clippy::excessive_precision, clippy::unreadable_literal, dead_code)]\n\n` +
  `pub const SCHEMA_VERSION: u32 = 1;\n` +
  `pub const SCHEMA_FINGERPRINT: u32 = ${fingerprint};\n` +
  `pub const PARAM_COUNT: usize = ${schema.params.length};\n` +
  Object.entries(constants).map(([key, value]) => `pub const ${key}: usize = ${value};\n`).join('') +
  `pub const NO_AUX_SOURCE: u32 = 0xffffffff;\n` +
  rustConst('PARAMETER_NAMES', '[&str; PARAM_COUNT]', schema.params.map(p => JSON.stringify(p.id))) +
  rustConst('DEFAULTS', '[f32; PARAM_COUNT]', floats(schema.params.map(p => p.default))) +
  rustConst('MINIMUM', '[f32; PARAM_COUNT]', floats(schema.params.map(p => p.min))) +
  rustConst('MAXIMUM', '[f32; PARAM_COUNT]', floats(schema.params.map(p => p.max))) +
  rustConst('LOGARITHMIC', '[bool; PARAM_COUNT]', bools(schema.params.map(p => p.scale === 'log'))) +
  rustConst('MODULATABLE', '[bool; PARAM_COUNT]', bools(schema.params.map(p => p.modulate))) +
  rustConst('INTEGER', '[bool; PARAM_COUNT]', bools(schema.params.map(p => p.integer || p.options?.every(o => Number.isInteger(o.value))))) +
  rustConst('OPTION_COUNT', '[u8; PARAM_COUNT]', schema.params.map(p => String(p.options?.length ?? 0))) +
  rustConst('OPTION_VALUES', '[[f32; 8]; PARAM_COUNT]', schema.params.map(p => floats(optionValues(p)))) +
  rustConst('FACTORY_HARMONICS', `[[[f32; ${limits.factoryHarmonics}]; ${limits.factoryFrames}]; ${limits.factoryBanks}]`,
    schema.factoryBanks.map(bank => bank.harmonics.map(floats)))

let stale = false
for (const [path, contents] of [
  [resolve(here, 'schema.generated.ts'), generatedTs],
  [resolve(here, '../../..', 'rust/garak-engine/src/wave/schema.rs'), generatedRust],
]) {
  if (process.argv.includes('--check')) {
    const existing = await readFile(path, 'utf8').catch(() => '')
    // Git may check text out with CRLF. Only that newline difference is ignored;
    // generated content and the semantic schema fingerprint remain unchanged.
    if (existing.replace(/\r\n/g, '\n') !== contents) { console.error(`Stale generated schema: ${path}`); stale = true }
  } else {
    await mkdir(dirname(path), { recursive: true })
    await writeFile(path, contents)
  }
}
if (stale) process.exitCode = 1
